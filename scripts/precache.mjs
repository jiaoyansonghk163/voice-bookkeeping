import { createHash } from "node:crypto";
import { readFile, readdir, stat, writeFile } from "node:fs/promises";
import path from "node:path";

/** Bump when returning visitors must drop a previous precache. */
const CACHE_GENERATION = "v3";

const root = path.resolve("out");

async function walk(dir) {
  const entries = await readdir(dir, { withFileTypes: true });
  const files = [];
  for (const entry of entries) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) files.push(...(await walk(full)));
    else files.push(full);
  }
  return files;
}

/** Cloudflare Pages 308s /page.html to /page. Cache the URL it actually serves. */
function canonicalAsset(urlPath) {
  if (urlPath === "/404.html") return null;
  if (urlPath === "/index.html") return "/";
  if (urlPath.endsWith(".html")) return urlPath.slice(0, -".html".length);
  return urlPath;
}

const files = await walk(root);
const exportedFiles = files
  .filter((file) => {
    const name = path.basename(file);
    if (name === "sw.js" || name.startsWith("_") || name.endsWith(".txt")) return false;
    return true;
  })
  .sort();
const exported = exportedFiles.map((file) =>
  encodeURI(`/${path.relative(root, file).split(path.sep).join("/")}`),
);

if (!exported.includes("/index.html")) {
  throw new Error("static export is missing out/index.html");
}

const urls = [...new Set(exported.map(canonicalAsset).filter(Boolean))].sort();
if (urls.some((url) => url.endsWith(".html"))) {
  throw new Error("precache list still contains an .html path");
}
if (!urls.includes("/")) {
  throw new Error("precache list is missing /");
}

const bodies = [];
for (const file of exportedFiles) {
  bodies.push(createHash("sha256").update(await readFile(file)).digest("hex"));
}
const hash = createHash("sha256")
  .update(`${CACHE_GENERATION}\n${urls.join("\n")}\n${bodies.join("\n")}`)
  .digest("hex")
  .slice(0, 12);
const source = `/* Generated by scripts/precache.mjs. Do not edit. */
const CACHE = "voice-ledger-${CACHE_GENERATION}-${hash}";
const ASSETS = ${JSON.stringify(urls, null, 2)};

async function materialize(response) {
  if (!response || response.redirected !== true) return response;
  return new Response(await response.blob(), {
    status: response.status,
    statusText: response.statusText,
    headers: response.headers,
  });
}

function extensionless(pathname) {
  let path = pathname;
  if (path.length > 1 && path.endsWith("/")) path = path.slice(0, -1);
  if (path === "/index.html") return "/";
  if (path.endsWith(".html")) return path.slice(0, -".html".length) || "/";
  return path;
}

self.addEventListener("install", (event) => {
  event.waitUntil(
    (async () => {
      const cache = await caches.open(CACHE);
      await Promise.all(
        ASSETS.map(async (asset) => {
          const response = await fetch(asset);
          if (!response.ok) throw new Error("precache " + asset + " failed");
          await cache.put(asset, await materialize(response));
        }),
      );
      await self.skipWaiting();
    })(),
  );
});

self.addEventListener("activate", (event) => {
  event.waitUntil(
    caches
      .keys()
      .then((keys) => Promise.all(keys.filter((key) => key !== CACHE).map((key) => caches.delete(key))))
      .then(() => self.clients.claim()),
  );
});

self.addEventListener("fetch", (event) => {
  const request = event.request;
  if (request.method !== "GET") return;
  const url = new URL(request.url);
  if (url.origin !== self.location.origin) return;
  if (url.pathname === "/sw.js") return;

  event.respondWith(
    (async () => {
      const path = extensionless(url.pathname);
      const cached =
        (await caches.match(request, { ignoreSearch: true })) ||
        (await caches.match(path, { ignoreSearch: true }));
      if (cached) return materialize(cached);
      try {
        return materialize(await fetch(request));
      } catch {
        if (request.mode === "navigate") {
          const fallback = (await caches.match(path, { ignoreSearch: true })) || (await caches.match("/"));
          if (fallback) return materialize(fallback);
        }
        return Response.error();
      }
    })(),
  );
});
`;

await stat(path.join(root, "index.html"));
await writeFile(path.join(root, "sw.js"), source);
console.log(`precache ${urls.length} files → out/sw.js (${hash})`);
