import { createHash } from "node:crypto";
import { readdir, stat, writeFile } from "node:fs/promises";
import path from "node:path";

const root = path.resolve("out");

async function walk(dir) {
  const entries = await readdir(dir, { withFileTypes: true });
  const files = [];
  for (const entry of entries) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) files.push(...(await walk(full)));
    else files.push(full);
  }
  return files;
}

const files = await walk(root);
const urls = files
  .filter((file) => {
    const name = path.basename(file);
    if (name === "sw.js" || name.startsWith("_") || name.endsWith(".txt")) return false;
    return true;
  })
  .map((file) => encodeURI(`/${path.relative(root, file).split(path.sep).join("/")}`))
  .sort();

if (!urls.includes("/index.html")) {
  throw new Error("static export is missing out/index.html");
}

const hash = createHash("sha256").update(urls.join("\n")).digest("hex").slice(0, 12);
const source = `/* Generated by scripts/precache.mjs. Do not edit. */
const CACHE = "voice-ledger-${hash}";
const ASSETS = ${JSON.stringify(urls, null, 2)};

self.addEventListener("install", (event) => {
  event.waitUntil(caches.open(CACHE).then((cache) => cache.addAll(ASSETS)).then(() => self.skipWaiting()));
});

self.addEventListener("activate", (event) => {
  event.waitUntil(
    caches
      .keys()
      .then((keys) => Promise.all(keys.filter((key) => key !== CACHE).map((key) => caches.delete(key))))
      .then(() => self.clients.claim()),
  );
});

self.addEventListener("fetch", (event) => {
  const request = event.request;
  if (request.method !== "GET") return;
  const url = new URL(request.url);
  if (url.origin !== self.location.origin) return;

  event.respondWith(
    (async () => {
      const cached = await caches.match(request, { ignoreSearch: true });
      if (cached) return cached;
      if (url.pathname === "/" || url.pathname.endsWith("/")) {
        const home = await caches.match("/index.html");
        if (home) return home;
      }
      try {
        return await fetch(request);
      } catch {
        if (request.mode === "navigate") {
          const home = await caches.match("/index.html");
          if (home) return home;
        }
        return Response.error();
      }
    })(),
  );
});
`;

await writeFile(path.join(root, "sw.js"), source);
console.log(`precache ${urls.length} files → out/sw.js (${hash})`);
